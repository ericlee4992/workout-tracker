"""Seeded equipment catalog content (ticket 20).

Transcribed from the manufacturer research kept in `docs/catalog-sources/`. Every
model name here was read off a manufacturer listing, manufacturer PDF, or (where
the research flagged it) an authorised dealer carrying the manufacturer's own SKU
codes. Nothing is extrapolated from a naming pattern: where the research recorded
a *line* but did not enumerate its members, the line is absent here rather than
invented.

Format: MANUFACTURERS = [(manufacturer, [(modelName, "exerciseKey+exerciseKey"), …])]
Exercise keys are defined in generate_seed_catalog.py.

Research caveats honoured (see docs/catalog-sources/*.md "Confidence" sections):
- Eleiko: its "strength machines" category is resold Precor. Only genuinely
  Eleiko items (cable machines, Prestera racks) appear here.
- Star Trac: today's Star Trac strength lines ship as Nautilus. Only the 8
  Star Trac-branded names actually sighted are here; the Nautilus lists were
  NOT rebranded.
- Matrix: `B`-suffix models are an upholstery trim of the same machine —
  collapsed into the single non-B entry.
- Gym80: `N`-suffix part numbers are distinct SKUs — kept separate.
- Hoist: RS-1xxx and RS-2xxx are coexisting generations; only the three RS-1xxx
  codes actually sighted are here.
- BH Fitness: PL150B and PL155B are both "Seated Triceps" on BH's own page —
  disambiguated in the display name so the picker is not ambiguous.
- Atlantis: dealer-sourced only, no manufacturer corroboration (lower confidence).
- Rows shipped in catalog version 1 keep their exact v1 name (their UUID is
  keyed on it, D24), even where the research prefers a different string.
"""

